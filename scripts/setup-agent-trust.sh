#!/usr/bin/env bash
# Setup script for distributing Mercury's CA cert to agent environments.
# Usage: setup-agent-trust.sh [--system] [--node] [--python] [--env-file PATH]
set -euo pipefail

CERT_PATH="${MERCURY_CA_CERT:-/etc/mercury/ca.pem}"

# Export the CA cert from the running daemon if possible
if command -v mercury-status &>/dev/null; then
    mercury-status ca-cert > "$CERT_PATH" 2>/dev/null || true
fi

if [ ! -f "$CERT_PATH" ]; then
    echo "ERROR: CA cert not found at $CERT_PATH" >&2
    echo "Start mercuryd first, or set MERCURY_CA_CERT to the cert path" >&2
    exit 1
fi

FINGERPRINT=$(openssl x509 -in "$CERT_PATH" -noout -fingerprint -sha256 2>/dev/null | cut -d= -f2 || echo "unknown")
echo "Mercury CA cert: $CERT_PATH"
echo "Fingerprint: ${FINGERPRINT}"

install_system() {
    echo "Installing system-wide CA trust..."
    if [ -d /usr/local/share/ca-certificates ]; then
        cp "$CERT_PATH" /usr/local/share/ca-certificates/mercury-ca.crt
        update-ca-certificates
    elif [ -d /etc/pki/ca-trust/source/anchors ]; then
        cp "$CERT_PATH" /etc/pki/ca-trust/source/anchors/mercury-ca.pem
        update-ca-trust
    else
        echo "WARNING: Unknown CA trust store layout" >&2
    fi
}

install_node() {
    echo "export NODE_EXTRA_CA_CERTS=\"$CERT_PATH\""
}

install_python() {
    echo "export SSL_CERT_FILE=\"$CERT_PATH\""
    echo "export REQUESTS_CA_BUNDLE=\"$CERT_PATH\""
}

write_env_file() {
    local dest="$1"
    {
        echo "# Mercury URL gateway CA trust — generated by setup-agent-trust.sh"
        echo "NODE_EXTRA_CA_CERTS=$CERT_PATH"
        echo "SSL_CERT_FILE=$CERT_PATH"
        echo "REQUESTS_CA_BUNDLE=$CERT_PATH"
        echo "CURL_CA_BUNDLE=$CERT_PATH"
    } > "$dest"
    echo "Wrote env file: $dest"
}

if [ $# -eq 0 ]; then
    echo ""
    echo "Usage: setup-agent-trust.sh [--system] [--node] [--python] [--env-file PATH]"
    echo ""
    echo "Options:"
    echo "  --system     Install CA cert system-wide (requires root)"
    echo "  --node       Print NODE_EXTRA_CA_CERTS export"
    echo "  --python     Print SSL_CERT_FILE and REQUESTS_CA_BUNDLE exports"
    echo "  --env-file   Write environment variables to a file"
    exit 0
fi

while [ $# -gt 0 ]; do
    case "$1" in
        --system) install_system; shift;;
        --node) install_node; shift;;
        --python) install_python; shift;;
        --env-file) write_env_file "$2"; shift 2;;
        *) echo "Unknown option: $1" >&2; exit 1;;
    esac
done
